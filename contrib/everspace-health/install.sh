set -euo pipefail
here=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
game='' binary='' bin_dir="$HOME/.local/bin"
config=${G13MAP_CONFIG:-${XDG_CONFIG_HOME:-$HOME/.config}/g13map}
feed=${G13MAP_SHIP_FILE:-${XDG_STATE_HOME:-$HOME/.local/state}/g13map/ship}
profile=everspace base=default cli=g13map focus=true configure=true window_class=RSG-Linux-Shipping
usage() {
  cat <<'EOF'
Usage: install.sh [OPTIONS]
  --game-dir DIR      native EVERSPACE directory (default: standard Steam paths)
  --binary FILE       reader (default: checkout build, then installed g13map-everspace)
  --bin-dir DIR      install reader and Steam wrapper (default: ~/.local/bin)
  --config-dir DIR   g13map configuration directory
  --feed FILE        host-visible ship feed (default: XDG_STATE_HOME/g13map/ship)
  --profile NAME     existing/new profile (default: everspace; preserves existing binds)
  --base-profile NAME copy this profile when creating one (default: default, if present)
  --g13map PROGRAM   ship-capable CLI (default: g13map)
  --window-class CLASS game window class (default: RSG-Linux-Shipping)
  --no-focus         leave window rules alone
  --no-profile       install reader/wrapper only
  --version          print installer version
  --help             show help
Build first: cargo build --release --no-default-features --bin g13map-everspace
No game/save files, Steam settings, services, privileges or packages are changed.
EOF
}
while (($#)); do
  case $1 in
    --help) usage; exit 0;;
    --version) echo 'everspace-g13-install 0.1.0'; exit 0;;
    --no-focus) focus=false; shift;;
    --no-profile) configure=false; shift;;
    --game-dir|--binary|--bin-dir|--config-dir|--feed|--profile|--base-profile|--g13map|--window-class)
      (($# >= 2)) || { echo "Missing value for $1" >&2; exit 2; }
      case $1 in
        --game-dir) game=$2;; --binary) binary=$2;; --bin-dir) bin_dir=$2;;
        --config-dir) config=$2;; --feed) feed=$2;; --profile) profile=$2;;
        --base-profile) base=$2;; --g13map) cli=$2;; --window-class) window_class=$2;;
      esac
      shift 2;;
    *) echo "Unknown option: $1" >&2; exit 2;;
  esac
done
if [[ -z $binary ]]; then
  if [[ -x $here/../../target/release/g13map-everspace ]]; then
    binary="$here/../../target/release/g13map-everspace"
  else
    binary=$(command -v g13map-everspace || true)
  fi
fi
for value in "$feed" "$window_class"; do
  [[ -n $value && $value != *$'\n'* && $value != *$'\r'* ]] || { echo 'Paths and window classes must be nonempty single lines' >&2; exit 2; }
done
if [[ -z $game ]]; then
  for candidate in "$HOME/.local/share/Steam/steamapps/common/EVERSPACE" "$HOME/.steam/steam/steamapps/common/EVERSPACE"; do
    if [[ -f $candidate/RSG/Binaries/Linux/RSG-Linux-Shipping ]]; then game=$candidate; break; fi
  done
fi
[[ -f $game/RSG/Binaries/Linux/RSG-Linux-Shipping ]] || { echo 'Native game missing; use --game-dir (Windows/Proton is unsupported)' >&2; exit 1; }
[[ -x $binary ]] || { echo 'Build the reader first or pass --binary FILE' >&2; exit 1; }
"$binary" --version
"$binary" --check-game "$game/RSG/Binaries/Linux/RSG-Linux-Shipping"
export G13MAP_CONFIG="$config"
if $configure; then
  [[ $profile != . && $profile != .. && $profile != */* && $profile != *\\* && $profile != *[[:cntrl:]]* && -n $profile && ${#profile} -le 200 && $profile != [[:space:]]* && $profile != *[[:space:]] ]] || { echo 'Invalid profile name' >&2; exit 2; }
  help=$("$cli" --help)
  [[ $help == *'profile ship'* ]] || { echo 'A ship-capable g13map (0.3.7+) is required' >&2; exit 1; }
  if [[ -f $config/profiles/$profile.bind ]]; then "$cli" show "$profile" >/dev/null; fi
fi
binary=$(realpath -- "$binary")
bin_dir=$(realpath -m -- "$bin_dir")
feed=$(realpath -m -- "$feed")
backup="${XDG_STATE_HOME:-$HOME/.local/state}/g13map/everspace-backups/$(date -u +%Y%m%dT%H%M%SZ)-$$"
mkdir -p -- "$backup"
for file in "$bin_dir/g13map-everspace" "$bin_dir/g13map-everspace-steam" "$config/ship-feed"; do
  if [[ -f $file ]]; then cp -p -- "$file" "$backup/$(basename -- "$file")"; fi
done
if $configure; then
  [[ ! -f $config/profiles/$profile.bind ]] || cp -p -- "$config/profiles/$profile.bind" "$backup/profile.bind"
  [[ ! -f $config/focus ]] || cp -p -- "$config/focus" "$backup/focus"
fi
printf 'Bin directory: %s\nConfig directory: %s\nProfile: %s\nFeed: %s\n' "$bin_dir" "$config" "$profile" "$feed" > "$backup/paths.txt"
mkdir -p -- "$bin_dir"
if [[ $binary != "$bin_dir/g13map-everspace" ]]; then
  install -m 755 -- "$binary" "$bin_dir/g13map-everspace.new"
  mv -- "$bin_dir/g13map-everspace.new" "$bin_dir/g13map-everspace"
fi
{
  printf '#!/usr/bin/env bash\n# Generated by everspace-health/install.sh\n'
  printf 'reader=%q\n' "$bin_dir/g13map-everspace"
  cat <<'EOF'
if [[ $# == 1 && ( $1 == --version || $1 == --help ) ]]; then
  exec "$reader" "$1"
fi
EOF
  # shellcheck disable=SC2016 # Variables expand when the generated wrapper runs.
  printf 'exec "$reader" --feed %q -- "$@"\n' "$feed"
} > "$bin_dir/g13map-everspace-steam.new"
chmod 755 "$bin_dir/g13map-everspace-steam.new"
mv -- "$bin_dir/g13map-everspace-steam.new" "$bin_dir/g13map-everspace-steam"
if $configure; then
  if [[ ! -f $config/profiles/$profile.bind ]]; then
    if [[ -n $base && -f $config/profiles/$base.bind ]]; then "$cli" profile create "$profile" "$base";
    else "$cli" profile create "$profile"; fi
  fi
  "$cli" profile ship "$profile" on
  printf '%s\n' "$feed" > "$config/ship-feed.new"
  mv -- "$config/ship-feed.new" "$config/ship-feed"
  if $focus; then "$cli" focus set "$window_class" "$profile"; fi
fi
echo "Backup: $backup"
printf 'Steam launch option (retain other arguments):\n%q %%command%%\n' "$bin_dir/g13map-everspace-steam"
echo 'The wrapper must precede %command%, so its own game child is readable without privileges.'
